const num = (v: number): string => (Math.round(v * 100) / 100).toString();

/**
 * Moves, scales and optionally mirrors path data (left to right about x = 0
 * before the move). Handles M L C S Q T H V Z in either case; no arcs.
 */
function xf(d: string, dx: number, dy: number, s = 1, flip = false): string {
  const tokens = d.match(/[a-zA-Z]|-?\d*\.?\d+/g) ?? [];
  const out: string[] = [];
  let cmd = '';
  let k = 0;
  for (const t of tokens) {
    if (/[a-zA-Z]/.test(t)) {
      cmd = t;
      k = 0;
      out.push(t);
      continue;
    }
    const v = Number(t);
    const abs = cmd !== cmd.toLowerCase();
    const c = cmd.toLowerCase();
    const isX = c === 'h' ? true : c === 'v' ? false : k % 2 === 0;
    const scaled = isX ? (flip ? -v : v) * s : v * s;
    const r = abs ? scaled + (isX ? dx : dy) : scaled;
    out.push(` ${num(r)}`);
    k++;
  }
  return out.join('').replace(/([a-zA-Z]) /g, '$1');
}

/**
 * A narrow leaf (willow, reed) as a closed sliver from x, y: `len` long,
 * pointing `deg` degrees from straight down (positive swings right), `w` wide.
 */
function sliver(x: number, y: number, len: number, deg: number, w = 0.8): string {
  const a = (deg * Math.PI) / 180;
  const ux = -Math.sin(a);
  const uy = Math.cos(a);
  const px = -uy;
  const py = ux;
  const at = (f: number, side: number): string =>
    `${num(x + ux * len * f + px * w * side)} ${num(y + uy * len * f + py * w * side)}`;
  const tip = `${num(x + ux * len)} ${num(y + uy * len)}`;
  return `M${num(x)} ${num(y)}C${at(0.3, 1)} ${at(0.7, 1)} ${tip}C${at(0.7, -1)} ${at(0.3, -1)} ${num(x)} ${num(y)}Z`;
}

